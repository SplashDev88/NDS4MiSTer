"""Emit an authored, stackless ARM maintenance routine and its instruction listing.

No guest memory, exceptions or debug register reads. This is an isolated ARM7
experiment, not a console save-state implementation. --check detects stale ROMs.
"""
import argparse
from pathlib import Path

BASE = 0x0F000000
BUF = BASE + 0x800
META = BASE + 0xF10
BANKS = [(0x1F, 15, 0x7F00), (0x11, 22, 0x7F00),
         (0x12, 30, 0x6000), (0x13, 33, 0x6000),
         (0x17, 36, 0x6000), (0x1B, 39, 0x6000)]


def generate():
    words = {}
    listing = []
    pc = 0
    literals = []

    def emit(word, description):
        nonlocal pc
        assert pc not in words
        words[pc] = word
        listing.append((pc, description))
        pc += 4

    def literal(reg, value):
        literals.append((pc, reg, value))
        emit(0, f'ldr r{reg}, =0x{value:08X}')

    def flush():
        for location, reg, value in literals:
            offset = pc - location - 8
            assert 0 <= offset < 4096
            words[location] = 0xE59F0000 | reg << 12 | offset
            emit(value, f'.word 0x{value:08X}')
        literals.clear()

    def branch(destination, name):
        offset = (destination - BASE - pc - 8) // 4
        emit(0xEA000000 | (offset & 0xFFFFFF), f'b {name}')

    emit(0xE58F0000 | (0x800 - 8), 'str r0, [pc, #snapshot-(pc+8)]')
    literal(0, BUF + 4)
    emit(0xE8807FFE, 'stmia r0, {r1-r14}')
    for mode, index, mask in BANKS:
        emit(0xE321F000 | mode | 0xC0, f'msr cpsr_c, #0x{mode | 0xC0:02X}')
        literal(0, BUF + index * 4)
        emit(0xE8A00000 | mask, f'stmia r0!, #register-mask=0x{mask:04X}')
        if mode != 0x1F:
            emit(0xE14F1000, 'mrs r1, spsr')
            emit(0xE5801000, 'str r1, [r0]')
    literal(0, META)
    emit(0xE890000E, 'ldmia r0, {r1-r3}')
    literal(0, BUF + 42 * 4)
    emit(0xE880000E, 'stmia r0, {r1-r3}')
    branch(BASE + 0xF00, 'PARK')
    flush()
    assert pc < 0x400

    pc = 0x400
    literal(0, BUF + 42 * 4)
    emit(0xE890000E, 'ldmia r0, {r1-r3}')
    literal(0, META)
    emit(0xE880000E, 'stmia r0, {r1-r3}')
    for mode, index, mask in BANKS:
        emit(0xE321F000 | mode | 0xC0, f'msr cpsr_c, #0x{mode | 0xC0:02X}')
        literal(0, BUF + index * 4)
        emit(0xE8B00000 | mask, f'ldmia r0!, #register-mask=0x{mask:04X}')
        if mode != 0x1F:
            emit(0xE5901000, 'ldr r1, [r0]')
            emit(0xE16FF001, 'msr spsr_fsxc, r1')
    literal(0, BUF + 43 * 4)
    emit(0xE5901000, 'ldr r1, [r0]')
    emit(0xE38110C0, 'orr r1, r1, #0xC0 ; mask interrupts during bank restore')
    emit(0xE3C11020, 'bic r1, r1, #0x20 ; stay ARM until hardware return')
    emit(0xE121F001, 'msr cpsr_c, r1')
    literal(0, BUF + 4)
    emit(0xE8907FFE, 'ldmia r0, {r1-r14}')
    offset = 0x800 - pc - 8
    assert 0 <= offset < 4096
    emit(0xE59F0000 | offset, 'ldr r0, [pc, #snapshot-(pc+8)]')
    branch(BASE + 0xF04, 'EXIT')
    flush()
    assert pc < 0x800
    header = '-- SPDX-License-Identifier: GPL-3.0-or-later\n' \
             '-- Generated by tools/suspend_resume/arm7_monitor_rom.py; do not edit.\n'
    vhdl = header + '''library ieee;
use ieee.std_logic_1164.all;
package nds_arm7_monitor_rom is
  type monitor_rom_type is array(0 to 511) of std_logic_vector(31 downto 0);
  constant MONITOR_ROM : monitor_rom_type := (
'''
    vhdl += ''.join(f'    {address//4} => x"{word:08X}",\n' for address, word in sorted(words.items()))
    vhdl += '    others => x"EAFFFFFE");\nend package;\n'
    asm = '; Generated authored ARM instruction listing (hex address / opcode).\n'
    asm += ''.join(f'{BASE+a:08X}  {words[a]:08X}  {description}\n' for a, description in listing)
    return vhdl, asm


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[2]
    for path, content in zip([repo/'rtl/nds_arm7_monitor_rom.vhd',
                             repo/'tools/suspend_resume/arm7_monitor_rom.lst'], generate()):
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('stale generated monitor ROM: ' + str(path))
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
