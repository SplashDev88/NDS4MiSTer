"""Launch a hash-checked, locally prepared private FMV fixture.

The adjacent registry is generated by the hardware qualification workflow.
It contains paths and hashes, never ROM or movie data. This is not a ROM patcher
or a general compatibility launcher.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def choose_game(games):
    require(sys.stdin.isatty(), "Select a prepared game with --game.")
    choices = list(games)
    message = "Private FMV test copies with separate saves. Choose a game."
    if shutil.which("dialog"):
        command = ["dialog", "--stdout", "--title", "NDS4MiSTer Movie Test",
                   "--menu", message, "18", "72", str(len(choices))]
        for number, key in enumerate(choices, 1):
            command.extend([str(number), games[key]["title"]])
        result = subprocess.run(command, stdout=subprocess.PIPE, text=True)
        if result.returncode:
            return None
        answer = result.stdout.strip()
    else:
        print(message)
        for number, key in enumerate(choices, 1):
            print("{}. {}".format(number, games[key]["title"]))
        answer = input("Number, or Enter to cancel: ").strip()
        if not answer:
            return None
    require(answer.isdigit() and 1 <= int(answer) <= len(choices),
            "No valid game selected.")
    return choices[int(answer) - 1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", help="Prepared game identifier from the registry")
    parser.add_argument("--validate-only", action="store_true")
    parser.add_argument("--seconds", type=int, default=0)
    parser.add_argument("--direct-video-target", choices=("crt", "retrotink"))
    args = parser.parse_args()
    require(0 <= args.seconds <= 3600, "Invalid bounded test duration.")

    kit = Path(__file__).resolve().parent
    registry_path = kit / "FMV_MOVIE_TEST.json"
    manifest = json.loads((kit / "manifest.json").read_text())
    require(manifest.get("private_test_ready") is True,
            "This private test package has not completed its required checks.")
    require(sha256(registry_path) == manifest.get("movie_test_registry_sha256"),
            "Movie-test registry does not match this package.")
    require(sha256(Path(__file__).resolve()) == manifest.get("movie_test_program_sha256"),
            "Movie-test launcher does not match this package.")
    registry = json.loads(registry_path.read_text())
    require(registry.get("version") == 1, "Unsupported movie-test registry.")
    require(set(registry["components"]) == {
        "NDS_Standalone.rbf", "nds_standalone_host", "supervisor.py",
        "Kickstart.sh", "support/nds_hybrid_3d_service"},
        "Incomplete movie-test component identity checks.")
    for name, expected in registry["components"].items():
        require(sha256(kit / name) == expected,
                "Mismatched component: " + name)

    game_key = args.game or choose_game(registry["games"])
    if game_key is None:
        return 0
    require(game_key in registry["games"], "Unknown prepared game.")
    game = registry["games"][game_key]
    source = Path(game["rom"])
    alias = Path(game["alias"])
    require(alias.parent == Path("/tmp") and
            alias.name.startswith("NDS FMV ") and alias.suffix == ".nds",
            "Invalid private ROM alias.")
    require(source.is_file(), "Prepared test copy is missing: " + game["title"])
    print("Checking private test copy: " + game["title"], flush=True)
    require(sha256(source) == game["sha256"],
            "Prepared test copy changed; launch cancelled.")
    with source.open("rb") as stream:
        header = stream.read(0x160)
    require(len(header) == 0x160 and header[12:16].decode("ascii") == game["code"]
            and header[30] == game["revision"], "Unexpected cartridge identity.")
    if args.validate_only:
        print("FMV_MOVIE_TEST_VALIDATION_PASS " + game_key)
        return 0

    require(Path("/tmp/CORENAME").read_text().strip() == "MENU",
            "Exit the current core with System -> Reboot before starting this test.")
    lease = Path("/tmp/nds-standalone-lease.json")
    require(not lease.exists() or json.loads(lease.read_text()).get("done"),
            "Another standalone session is still active.")
    if alias.is_symlink():
        require(alias.resolve() == source.resolve(), "Private ROM alias changed.")
    else:
        require(not alias.exists(), "Private ROM alias is occupied.")
        alias.symlink_to(source)
    save = Path("/media/fat/saves/NDS") / (alias.stem + ".sav")
    if not save.exists():
        with save.open("xb"):
            pass
    require(save.is_file() and not save.is_symlink(), "Invalid private save file.")

    command = [sys.executable, str(kit / "supervisor.py"),
               "--rom", str(alias), "--seconds", str(args.seconds)]
    if args.direct_video_target:
        command.extend(["--direct-video-target", args.direct_video_target])
    environment = os.environ.copy()
    environment["NDS_FMV_COLOR_FAST"] = "1"
    print("Starting {}. These are separate test saves.".format(game["title"]), flush=True)
    os.execve(sys.executable, command, environment)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, OSError, ValueError, KeyError) as error:
        print("NDS4MiSTer Movie Test: " + str(error), file=sys.stderr)
        if sys.stdin.isatty():
            input("Press Enter to return to MiSTer.")
        sys.exit(1)
