inline uint32_t crc32(const uint8_t* data, size_t size) {
  uint32_t crc = ~0u;
  for (size_t i=0; i<size; ++i) {
    crc ^= data[i];
    for (unsigned bit=0; bit<8; ++bit) crc=(crc>>1)^(0xedb88320u & (0u-(crc&1u)));
  }
  return ~crc;
}
